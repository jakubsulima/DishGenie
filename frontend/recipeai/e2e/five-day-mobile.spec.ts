import { test, expect } from '@playwright/test';
const backend = process.env.RECIPEAI_BROWSER_BACKEND;
test.use({timezoneId:'Europe/Warsaw',isMobile:true,hasTouch:true});
test.skip(!backend, 'Requires isolated BrowserPlannerSmokeIT backend');
for (const width of [360,390]) test(`five day mobile journey ${width}`, async ({page}) => {
 test.setTimeout(120000); await page.setViewportSize({width,height:844});
 await page.addInitScript(()=>{localStorage.setItem('dishGenie.locale','pl');localStorage.setItem('isLoggedIn','true');});
 const csrf=await(await page.request.get(`${backend}/api/csrf`)).json();
 const token=(await page.context().cookies()).find(c=>c.name==='XSRF-TOKEN')!.value;
 expect((await page.request.post(`${backend}/api/login`,{headers:{[csrf.headerName]:decodeURIComponent(token)},data:{email:`browser-cycle-${width}@example.com`,password:'Browser-test-only-123!'}})).ok()).toBe(true);
 await page.goto('/ShoppingList');
 const refresh=page.waitForResponse(r=>r.url().endsWith('/offers/reload-prices'));
 await page.getByRole('button',{name:'Pobierz promocje',exact:true}).tap(); expect((await refresh).ok()).toBe(true);
 await expect(page.getByText(/Dostępne produkty z obsługiwaną ceną:/)).toBeVisible();
 await expect(page.getByText('Ryż — kontrolowane dane testowe',{exact:true})).toBeHidden();
 await page.getByText('Zobacz promocje (1)',{exact:true}).tap();
 await expect(page.getByText('Ryż — kontrolowane dane testowe',{exact:true})).toBeVisible();
 await page.getByText('Zobacz promocje (1)',{exact:true}).tap();
 await page.screenshot({path:`/tmp/five-day-offers-${width}.png`,fullPage:true});
 await page.getByRole('link',{name:'Mój tydzień',exact:true}).tap();
 await page.getByLabel('Liczba dni',{exact:true}).fill('5');
 for (const name of ['Śniadanie','Obiad','Kolacja']) await page.getByRole('checkbox',{name,exact:true}).check();
 await page.screenshot({path:`/tmp/five-day-form-${width}.png`,fullPage:true});
 const started=page.waitForResponse(r=>r.url().endsWith('/v4/meal-plans/start')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Zaplanuj tydzień',exact:true}).tap();
 const response=await started; expect(response.ok(),await response.text()).toBe(true); const created=await response.json();
 expect(created.view.plan.settings.mealTypes).toHaveLength(3); expect(created.view.plan.settings.planningMode).toBe('PROMOTIONS_FIRST');
 await expect(page.getByText(/15 z 15 posiłków/)).toBeVisible({timeout:90000});
 const plan=await(await page.request.get(`${backend}/api/v4/meal-plans/${created.view.id}`)).json();
 expect(plan.plan.slots).toHaveLength(15);expect(plan.plan.slots.every((s:{recipe:unknown})=>s.recipe)).toBe(true);
 for(const type of ['BREAKFAST','LUNCH','DINNER']) expect(plan.plan.slots.filter((s:{mealType:string})=>s.mealType===type)).toHaveLength(5);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`/tmp/five-day-week-${width}.png`,fullPage:true});
 await page.getByRole('button',{name:'Przejdź do zakupów',exact:true}).tap();
 await expect(page.getByRole('heading',{name:'Lista zakupów',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Pobierz promocje',exact:true})).toHaveCount(0);
 const shopping=await(await page.request.get(`${backend}/api/v4/meal-plans/${created.view.id}/shopping-preview`)).json();
 expect(shopping.items.find((i:{name:string})=>i.name==='ryż').amount).toBe(4300);
 await expect(page.getByRole('checkbox',{name:/ryż/})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`/tmp/five-day-shopping-${width}.png`,fullPage:true});
 await page.reload();await expect(page.getByRole('checkbox',{name:/ryż/})).toBeVisible();
});
