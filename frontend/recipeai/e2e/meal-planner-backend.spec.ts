import { expect, test } from "@playwright/test";
const backend = process.env.RECIPEAI_BROWSER_BACKEND;
test.skip(!backend, "Opt-in real local backend with controlled Gemini; started by BrowserPlannerSmokeIT.");
for (const mobile of [true, false]) {
  test(`real backend: settings, week, revision, shops, refresh ${mobile ? "PL mobile" : "EN desktop"}`, async ({ page }) => {
    test.setTimeout(60000);
    await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 });
    await page.addInitScript(pl => { localStorage.setItem("dishGenie.locale", pl ? "pl" : "en"); localStorage.setItem("isLoggedIn", "true"); }, mobile);
    const csrf = await (await page.request.get(`${backend}/api/csrf`)).json();
    const token = (await page.context().cookies()).find(c => c.name === "XSRF-TOKEN")!.value;
    const login = await page.request.post(`${backend}/api/login`, { headers: { [csrf.headerName]: decodeURIComponent(token) }, data: { email: `browser-planner-${mobile ? "pl" : "en"}@example.com`, password: "Browser-test-only-123!" } });
    expect(login.ok()).toBe(true);
    await page.goto("/MealPlanner");
    const create = page.getByRole("button", { name: mobile ? "Utwórz jadłospis" : "Create meal plan" });
    await expect(create).toBeEnabled();
    await page.getByLabel(mobile ? "Liczba dni" : "Number of days").fill(mobile ? "7" : "1");
    const createdResponse = page.waitForResponse(r => r.request().method() === "POST" && /v3\/meal-plans$/.test(new URL(r.url()).pathname));
    await create.click();
    const created = await createdResponse;
    expect(created.status(), await created.text()).toBe(200);
    const queued = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname.endsWith("/generations"));
    await page.getByRole("button", { name: mobile ? "Zaplanuj brakujące posiłki" : "Generate missing meals" }).click();
    expect((await queued).status()).toBe(202);
    await page.reload();
    await expect(page.getByText(mobile ? "Zaplanowane posiłki: 14" : "2 meals planned", { exact: true })).toBeVisible({ timeout: 40000 });
    await expect(page.getByText(mobile ? "39,90" : "3.99", { exact: false }).first()).toBeVisible();
    await page.getByRole("button", { name: mobile ? "Ustawienia planera" : "Planner settings" }).click();
    await page.getByLabel(mobile ? "Orientacyjna kwota (PLN, opcjonalnie)" : "Budget for this plan (PLN)").fill("0.01");
    await page.getByRole("button", { name: mobile ? "Zapisz ustawienia planera" : "Save planner settings" }).click();
    await expect(page.getByText(mobile ? "Znane koszty przekraczają budżet" : "Known costs exceed your budget")).toBeVisible();
    await page.getByRole("button", { name: mobile ? "Zaakceptuj plan i utwórz listę zakupów" : "Accept plan and create shopping list" }).click();
    await page.getByRole("checkbox", { name: "ryż", exact: true }).check();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: mobile ? "Popraw przepis" : "Improve recipe" }).first().click();
    await page.getByLabel(mobile ? "Ilość 1" : "Quantity 1").fill("400");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    if (mobile) await page.screenshot({ path: "/tmp/meal-planner-mobile-editor.png" });
    await page.getByRole("button", { name: mobile ? "Podgląd zmiany" : "Preview change" }).click();
    await expect(page.getByText(mobile ? "Zakupy po zmianie:" : "Shopping after:", { exact: false })).toBeVisible();
    await page.getByRole("button", { name: mobile ? "Zastosuj poprawkę" : "Apply this change" }).click();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).not.toBeChecked();
    await page.getByRole("button", { name: mobile ? "Wybierz ten koszyk do zakupów" : "Use this basket for shopping" }).click();
    await expect(page.getByRole("heading", { name: mobile ? "Lidl · Produkty suche" : "Lidl · Dry goods" })).toBeVisible();
    await page.getByText(mobile ? "Brak produktu lub inna cena?" : "Product unavailable or price different?").click();
    await page.getByRole("button", { name: mobile ? "Zapisz zgłoszenie" : "Save report" }).click();
    await expect(page.getByText(mobile ? "Zgłoszenie zapisane. Plan i ceny dla innych użytkowników pozostają bez zmian." : "Report saved. Your plan and global prices are unchanged.")).toBeVisible();
    await page.getByRole("checkbox", { name: "ryż", exact: true }).check();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeEnabled();
    await page.reload();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeChecked();
    await expect(page.getByRole("heading", { name: mobile ? "Lidl · Produkty suche" : "Lidl · Dry goods" })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `/tmp/meal-planner-real-backend-${mobile ? "pl-mobile" : "en-desktop"}.png`, fullPage: true });
  });
}
