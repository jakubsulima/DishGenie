import { expect, test } from "@playwright/test";
const backend = process.env.RECIPEAI_BROWSER_BACKEND;
test.skip(!backend, "Opt-in real local backend with controlled Gemini; started by BrowserPlannerSmokeIT.");
for (const mobile of [true, false]) {
  test(`real backend: settings, week, revision, shops, refresh ${mobile ? "PL mobile" : "EN desktop"}`, async ({ page }) => {
    test.setTimeout(90000);
    page.setDefaultTimeout(10000);
    await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 });
    await page.addInitScript(pl => { localStorage.setItem("dishGenie.locale", pl ? "pl" : "en"); localStorage.setItem("isLoggedIn", "true"); }, mobile);
    const csrf = await (await page.request.get(`${backend}/api/csrf`)).json();
    const token = (await page.context().cookies()).find(c => c.name === "XSRF-TOKEN")!.value;
    const login = await page.request.post(`${backend}/api/login`, { headers: { [csrf.headerName]: decodeURIComponent(token) }, data: { email: `browser-planner-${mobile ? "pl" : "en"}@example.com`, password: "Browser-test-only-123!" } });
    expect(login.ok()).toBe(true);
    const day = new Date(); const startDate = `${day.getFullYear()}-${String(day.getMonth()+1).padStart(2,"0")}-${String(day.getDate()).padStart(2,"0")}`;
    const legacy = await page.request.post(`${backend}/api/v3/meal-plans`, {headers:{[csrf.headerName]:decodeURIComponent(token)},data:{requestId:crypto.randomUUID(),startDate,dayCount:mobile?7:1,servings:2,mealTypes:["LUNCH","DINNER"],stores:["LIDL"],budget:null,locale:"pl",maxMinutes:45,planningMode:"PROMOTIONS_FIRST",budgetMode:"NONE",shopping:{shoppingDate:startDate,maxStores:1,loyaltyStores:[],confirmedCouponOffers:[],selectedOffers:[],allowRepeats:false}}});
    expect(legacy.ok(),await legacy.text()).toBe(true);
    await page.goto(`/MealPlanner?plan=${(await legacy.json()).id}`);
    const queued = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname.endsWith("/generations"));
    await page.getByRole("button", { name: mobile ? "Zaplanuj tydzień" : "Plan the week" }).click();
    expect((await queued).status()).toBe(202);
    await page.reload();
    await expect(page.getByText(mobile ? "2 os. · 14 z 14 posiłków" : "2 people · 2 of 2 meals", { exact: true })).toBeVisible({ timeout: 40000 });
    await page.getByRole("button", { name: mobile ? "Opcje planu" : "Plan options" }).click();
    await page.getByRole("button", { name: mobile ? "Ustawienia planera" : "Planner settings" }).click();
    await page.getByText(mobile ? "Dostosuj" : "Customize", { exact: true }).click();
    await page.getByLabel(mobile ? "Orientacyjna kwota (PLN, opcjonalnie)" : "Budget for this plan (PLN)").fill("0.01");
    await page.getByRole("button", { name: mobile ? "Zapisz ustawienia planera" : "Save planner settings" }).click();
    await page.getByRole("button", { name: mobile ? "Przejdź do zakupów" : "Go to shopping" }).click();
    await page.getByText(mobile ? "Porównaj koszt zakupów" : "Compare shopping costs", { exact: true }).click();
    await expect(page.getByText(mobile ? "Znane koszty przekraczają budżet" : "Known costs exceed your budget")).toBeVisible();
    await page.getByRole("button", { name: mobile ? "Zaakceptuj plan i utwórz listę zakupów" : "Accept plan and create shopping list" }).click();
    await page.getByRole("checkbox", { name: "ryż", exact: true }).check();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: mobile ? "Tydzień" : "Week", exact: true }).click();
    await page.getByRole("button", { name: mobile ? "Opcje dania" : "Meal options" }).first().click();
    await page.getByRole("button", { name: mobile ? "Edytuj przepis" : "Edit recipe", exact: true }).click();
    await page.getByLabel(mobile ? "Ilość 1" : "Quantity 1").fill("400");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    if (mobile) await page.screenshot({ path: "/tmp/meal-planner-mobile-editor.png" });
    await page.getByRole("button", { name: mobile ? "Podgląd zmiany" : "Preview change" }).click();
    await expect(page.getByText(mobile ? "Zakupy po zmianie:" : "Shopping after:", { exact: false })).toBeVisible();
    await page.getByRole("button", { name: mobile ? "Zastosuj poprawkę" : "Apply this change" }).click();
    await page.getByRole("button", { name: mobile ? "Zamknij" : "Close", exact: true }).click();
    await page.getByRole("button", { name: mobile ? "Zakupy" : "Shopping", exact: true }).click();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).not.toBeChecked();
    await page.getByRole("button", { name: mobile ? "Wybierz ten koszyk do zakupów" : "Use this basket for shopping" }).click();
    await expect(page.getByRole("heading", { name: mobile ? "Lidl · Produkty suche" : "Lidl · Dry goods" })).toBeVisible();
    await page.getByText(mobile ? "Brak produktu lub inna cena?" : "Product unavailable or price different?").click();
    await page.getByRole("button", { name: mobile ? "Zapisz zgłoszenie" : "Save report" }).click();
    await expect(page.getByText(mobile ? "Zgłoszenie zapisane. Plan i ceny dla innych użytkowników pozostają bez zmian." : "Report saved. Your plan and global prices are unchanged.")).toBeVisible();
    await page.getByRole("checkbox", { name: "ryż", exact: true }).check();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeEnabled();
    await page.reload();
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeChecked();
    await expect(page.getByRole("heading", { name: mobile ? "Lidl · Produkty suche" : "Lidl · Dry goods" })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByText(mobile ? "Porównaj koszt zakupów" : "Compare shopping costs", { exact: true }).click();
    await page.getByText(mobile ? "Produkty i warunki zakupów" : "Shopping details and conditions", { exact: true }).click();
    await page.getByRole("button", { name: mobile ? "Dodaj znaną cenę" : "Add a known price" }).click();
    await page.getByLabel(mobile ? "Ilość w jednym opakowaniu (g)" : "Amount in one package (g)").fill("400");
    await page.getByLabel(mobile ? "Cena za opakowanie (PLN)" : "Price per package (PLN)").fill("2.50");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const savedPrice = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname.endsWith("/prices"));
    const repriced = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname.endsWith("/quote-preview"));
    await page.getByRole("button", { name: mobile ? "Zapisz cenę" : "Save price", exact: true }).click();
    expect((await savedPrice).status()).toBe(200);
    const privateQuote = await (await repriced).json();
    expect(privateQuote.baskets[0].knownTotal).toBe(mobile ? 25 : 2.5);
    expect(privateQuote.baskets[0].items[0].manualPrice.packagePrice).toBe(2.5);
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeChecked();
    await page.reload();
    await page.getByText(mobile ? "Porównaj koszt zakupów" : "Compare shopping costs", { exact: true }).click();
    await page.getByText(mobile ? "Produkty i warunki zakupów" : "Shopping details and conditions", { exact: true }).click();
    await expect(page.getByText(mobile ? "Twoja cena, tylko w tym planie" : "Your price, private to this plan", { exact: false }).first()).toBeVisible();
    await page.getByRole("button", { name: mobile ? "Edytuj swoją cenę" : "Edit your price" }).click();
    const removedPrice = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname.endsWith("/remove"));
    await page.getByRole("button", { name: mobile ? "Usuń swoją cenę" : "Remove your price" }).click();
    expect((await removedPrice).status()).toBe(200);
    await expect(page.getByRole("checkbox", { name: "ryż", exact: true })).toBeChecked();
    if (!mobile) {
      await page.getByRole("button", { name: "Week", exact: true }).click();
      const meals = page.locator('article[id^="meal-slot-"]');
      const firstName = await meals.first().getByRole("heading", { level: 4 }).innerText();
      const secondName = await meals.nth(1).getByRole("heading", { level: 4 }).innerText();
      await page.getByRole("button", { name: "Meal options", exact: true }).first().click();
      await page.getByRole("button", { name: "Keep when replanning", exact: true }).click();
      await page.getByRole("button", { name: "Shopping", exact: true }).click();
      await page.getByText("Offers and replanning", { exact: true }).click();
      const replan = page.getByRole("button", { name: "Build plan from these offers" });
      await expect(replan).toBeEnabled();
      const queuedReplan = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname.endsWith("/replan-from-offers"));
      await replan.click();
      expect((await queuedReplan).status()).toBe(202);
      await expect(page.getByText("Ready · 1/1")).toBeVisible({ timeout: 30000 });
      await page.getByRole("button", { name: "Week", exact: true }).click();
      await expect(meals.first().getByRole("heading", { level: 4 })).toHaveText(firstName);
      await expect(meals.nth(1).getByRole("heading", { level: 4 })).not.toHaveText(secondName);
      await expect(page.getByText("Kept when replanning", { exact: true })).toBeVisible();
    }
    await page.screenshot({ path: `/tmp/meal-planner-real-backend-${mobile ? "pl-mobile" : "en-desktop"}.png`, fullPage: true });
  });
}
